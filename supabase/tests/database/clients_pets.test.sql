select is((select count(*)::integer from public.pets where id=current_setting('test.pet')::uuid),1,'Mascota preservada');
reset role;
select set_config('request.jwt.claim.sub',current_setting('test.client'),true);
set local role authenticated;
select is((select count(*)::integer from public.pets),0,'Padre retirado oculta mascota');
select throws_ok($$select public.retire_pet(current_setting('test.pet')::uuid)$$,'42501',null,'Cliente no retira');
reset role;
